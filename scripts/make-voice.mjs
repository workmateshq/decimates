// Records the announcer's lines (every prompt, "Caption this comic" and the stingers) with the Kokoro
// text-to-speech model, voice bm_daniel (British male), into public/sound/voice/ as small MP3s, and writes
// public/js/voice.js mapping each line's text to its file. Lines already recorded are skipped, so run it
// again after adding prompts.
//
//   npm install --no-save kokoro-js     (downloads the ~90 MB model on first run; nothing is uploaded)
//   node scripts/make-voice.mjs
//
// Needs ffmpeg on the PATH for the WAV -> MP3 step.
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const VOICE = 'bm_daniel';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const Prompts = require(path.join(root, 'public/js/prompts.js'));
const outDir = path.join(root, 'public/sound/voice');
fs.mkdirSync(outDir, { recursive: true });

const lines = [...new Set([...Prompts.PROMPTS, Prompts.COMIC_PROMPT, ...Prompts.STINGER_LINES])];
// Blanks ("___") are read as "blank".
const spoken = (text) => text.replace(/_{2,}/g, 'blank');
const fileFor = (text) => `${createHash('sha1').update(`${VOICE}|${text}`).digest('hex').slice(0, 12)}.mp3`;

const { KokoroTTS } = await import('kokoro-js');
const tts = await KokoroTTS.from_pretrained('onnx-community/Kokoro-82M-v1.0-ONNX', { dtype: 'q8', device: 'cpu' });

const map = {};
let made = 0;
for (const [i, text] of lines.entries()) {
  const file = fileFor(text);
  const mp3 = path.join(outDir, file);
  map[text] = `sound/voice/${file}`;
  if (fs.existsSync(mp3)) continue;
  const audio = await tts.generate(spoken(text), { voice: VOICE });
  const wav = path.join(outDir, `${file}.wav`);
  await audio.save(wav);
  execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', wav, '-ac', '1', '-b:a', '56k', mp3]);
  fs.unlinkSync(wav);
  made += 1;
  process.stdout.write(`\r${i + 1}/${lines.length} ${text.slice(0, 50).padEnd(50)}`);
}

// Drop recordings for lines that no longer exist.
const keep = new Set(Object.values(map).map((u) => path.basename(u)));
fs.readdirSync(outDir).filter((f) => f.endsWith('.mp3') && !keep.has(f)).forEach((f) => fs.unlinkSync(path.join(outDir, f)));

fs.writeFileSync(path.join(root, 'public/js/voice.js'),
  `// Generated by scripts/make-voice.mjs: each announcer line's text -> its recording (Kokoro ${VOICE}).\n`
  + `window.DECIMATES_VOICE = ${JSON.stringify(map, null, 2)};\n`);
console.log(`\n${made} new recording(s), ${lines.length} lines in public/js/voice.js`);
